import { NextResponse, after, type NextRequest } from 'next/server'
import { supabaseAdmin } from '@/lib/supabase-server'
import { logger } from '@/lib/logger'
import { validateBody, emailAgentCallbackSchema } from '@/lib/validation'
import { setEncryptedToken } from '@/lib/oauth/tokens'

// ── Reçoit le code OAuth Google, échange en tokens, stocke dans Supabase ─────
export async function GET(request: NextRequest) {
  const params = Object.fromEntries(request.nextUrl.searchParams)
  const v = validateBody(emailAgentCallbackSchema, params)
  if (!v.success) return NextResponse.json({ error: v.error }, { status: 400 })

  const { code, state, error } = v.data

  const APP_URL = process.env.NEXT_PUBLIC_APP_URL || ''

  if (error || !code || !state) {
    return NextResponse.redirect(`${APP_URL}/syndic/v54?email_error=${error || 'missing_code'}`)
  }

  // CSRF: state = syndic_id:nonce — extract and verify
  const stateParts = state.split(':')
  const syndicId = stateParts[0]
  const nonce = stateParts[1]

  if (!syndicId || !/^[0-9a-f-]{36}$/i.test(syndicId) || !nonce) {
    return NextResponse.redirect(`${APP_URL}/syndic/v54?email_error=invalid_state`)
  }

  // ── Verify the nonce was generated by our connect route ──
  const { data: tokenRow } = await supabaseAdmin
    .from('syndic_oauth_tokens')
    .select('oauth_nonce, oauth_nonce_expires_at')
    .eq('syndic_id', syndicId)
    .single()

  if (!tokenRow?.oauth_nonce || tokenRow.oauth_nonce !== nonce) {
    logger.error('OAuth CSRF: nonce mismatch for syndic', syndicId)
    return NextResponse.redirect(`${APP_URL}/syndic/v54?email_error=csrf_failed`)
  }

  // Check nonce expiry (10 min window)
  if (tokenRow.oauth_nonce_expires_at && new Date(tokenRow.oauth_nonce_expires_at) < new Date()) {
    logger.error('OAuth CSRF: nonce expired for syndic', syndicId)
    return NextResponse.redirect(`${APP_URL}/syndic/v54?email_error=state_expired`)
  }

  const GOOGLE_CLIENT_ID = process.env.GOOGLE_CLIENT_ID
  const GOOGLE_CLIENT_SECRET = process.env.GOOGLE_CLIENT_SECRET
  if (!GOOGLE_CLIENT_ID || !GOOGLE_CLIENT_SECRET) {
    logger.error('Missing Google OAuth env vars')
    return NextResponse.json({ error: 'Server configuration error' }, { status: 500 })
  }

  try {
    // 1. Échanger le code contre des tokens
    const tokenRes = await fetch('https://oauth2.googleapis.com/token', {
      method: 'POST',
      headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
      body: new URLSearchParams({
        code,
        client_id: GOOGLE_CLIENT_ID,
        client_secret: GOOGLE_CLIENT_SECRET,
        redirect_uri: `${APP_URL}/api/email-agent/callback`,
        grant_type: 'authorization_code',
      }),
    })

    const tokenData = await tokenRes.json()

    if (!tokenRes.ok || !tokenData.access_token) {
      logger.error('Token exchange error:', { error: tokenData?.error, error_description: tokenData?.error_description })
      return NextResponse.redirect(`${APP_URL}/syndic/v54?email_error=token_exchange`)
    }

    // 2. Récupérer l'email du compte Gmail connecté
    const profileRes = await fetch('https://www.googleapis.com/oauth2/v2/userinfo', {
      headers: { Authorization: `Bearer ${tokenData.access_token}` },
    })
    const profile = await profileRes.json()
    const emailCompte = profile.email || 'Inconnu'

    // 3. Calculer l'expiration du token
    const tokenExpiry = new Date(Date.now() + (tokenData.expires_in || 3600) * 1000).toISOString()

    // 4. Stocker les tokens dans Supabase (dual-write : encrypted + plain pour compat) + clear nonce
    // 4a. Écriture chiffrée via wrapper (Plan B). Non bloquante : la clé est passée par
    // set_config(is_local) dans une requête séparée de l'appel RPC, ce qui échoue en
    // production ; les colonnes en clair (4b) restent la source lue par poll en repli.
    try {
      await setEncryptedToken(supabaseAdmin, {
        syndic_id: syndicId,
        access_token: tokenData.access_token,
        refresh_token: tokenData.refresh_token || '',
        expires_at: tokenExpiry,
      })
    } catch (encryptErr) {
      logger.warn('[email-agent/callback] setEncryptedToken indisponible, tokens gardés en colonnes en clair', {
        erreur: encryptErr instanceof Error ? encryptErr.message.slice(0, 200) : String(encryptErr).slice(0, 200),
      })
    }

    // 4b. Dual-write plain + colonnes métier (Plan D supprimera les colonnes plain)
    const { error: upsertError } = await supabaseAdmin
      .from('syndic_oauth_tokens')
      .upsert({
        syndic_id: syndicId,
        provider: 'gmail',
        access_token: tokenData.access_token,
        refresh_token: tokenData.refresh_token || '',
        token_expiry: tokenExpiry,
        email_compte: emailCompte,
        scope: tokenData.scope || '',
        oauth_nonce: null,
        oauth_nonce_expires_at: null,
        updated_at: new Date().toISOString(),
      }, { onConflict: 'syndic_id' })

    if (upsertError) {
      logger.error('Supabase upsert error:', upsertError)
      return NextResponse.redirect(`${APP_URL}/syndic/v54?email_error=db_error`)
    }

    // 5. Première relève (30 jours) pour CE cabinet seulement, après l'envoi de la
    // réponse : after() s'appuie sur ctx.waitUntil du Worker (un fetch « fire-and-forget »
    // pouvait être annulé dès la redirection — cf. webhook ALF-1).
    const internalToken = process.env.INTERNAL_POLL_TOKEN || ''
    if (APP_URL && internalToken) {
      try {
        after(async () => {
          try {
            const pollRes = await fetch(`${APP_URL}/api/email-agent/poll`, {
              method: 'POST',
              headers: { 'Content-Type': 'application/json', 'x-internal-trigger': internalToken },
              body: JSON.stringify({ syndic_id: syndicId, first_run: true }),
            })
            if (!pollRes.ok) logger.warn('[email-agent/callback] première relève non-ok', { status: pollRes.status })
          } catch (err: unknown) {
            logger.warn('[email-agent/callback] première relève échouée', { erreur: err instanceof Error ? err.message : String(err) })
          }
        })
      } catch (err: unknown) {
        logger.warn('[email-agent/callback] after() indisponible, première relève non lancée', { erreur: err instanceof Error ? err.message : String(err) })
      }
    } else {
      logger.warn('[email-agent/callback] NEXT_PUBLIC_APP_URL ou INTERNAL_POLL_TOKEN absent : première relève non lancée')
    }

    return NextResponse.redirect(`${APP_URL}/syndic/v54?email_connected=true&email=${encodeURIComponent(emailCompte)}`)

  } catch (err: unknown) {
    logger.error('[email-agent/callback] OAuth error:', err)
    return NextResponse.redirect(`${APP_URL}/syndic/v54?email_error=server_error`)
  }
}
